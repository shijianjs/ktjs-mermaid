"""Generate the Kotlin declarations of mermaid's `MermaidConfig` tree.

Source of truth is the published TypeScript declaration of the npm package the wrapper locks
(`node_modules/mermaid/dist/config.type.d.ts`, installed by `kotlinNpmInstall`). Every interface,
every member and every string-literal union in that file is translated, so the Kotlin side never
falls back to `JsAny` where upstream declares a type.

Usage:

    python scripts/generate-config.py [--dts PATH] [--version X]

The output carries a `Generated by` marker and is rewritten wholesale on every run, so hand edits
are lost: change the mapping here, or exclude something deliberately and record why in
`docs/development/coverage.md`.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_DTS = os.path.join(ROOT, "node_modules", "mermaid", "dist", "config.type.d.ts")
OUT = os.path.join(
    ROOT, "ktjs-mermaid", "src", "jsMain", "kotlin", "io", "github", "shijianjs", "ktjs", "mermaid",
    "config", "ConfigTypes.kt",
)
PKG = "io.github.shijianjs.ktjs.mermaid.config"

KOTLIN_KEYWORDS = {
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface",
    "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias",
    "typeof", "val", "var", "when", "while",
}

HEADER = """// Generated by scripts/generate-config.py from mermaid@{version} dist/config.type.d.ts.
// Do not edit: rerun the generator instead. Anything Kotlin cannot express is handled by the
// mapping tables in that script; anything not generated on purpose is listed in
// docs/development/coverage.md.

package {package}

import js.objects.Record
import kotlin.js.JsAny
import kotlin.js.JsName
import kotlin.js.unsafeCast

"""

PRELUDE = """// ---------------------------------------------------------------------------------------------
// The unions the generated members refer to. Declared here rather than generated because the same
// shape is shared by dozens of members and a per-field name would just be noise.
// ---------------------------------------------------------------------------------------------

/**
 * `string | number`: a value that may be a number or a CSS string such as `"12px"`.
 *
 * Kotlin has no literal union types, so callers wrap the value explicitly:
 * `StringOrDouble("12px")` or `StringOrDouble(12.0)`.
 */
external interface StringOrDouble

/** Wraps the `String` half of [StringOrDouble]. */
@Suppress("NOTHING_TO_INLINE")
inline fun StringOrDouble(value: String): StringOrDouble = value.unsafeCast<StringOrDouble>()

/** Wraps the `Double` half of [StringOrDouble]. */
@Suppress("NOTHING_TO_INLINE")
inline fun StringOrDouble(value: Double): StringOrDouble = value.unsafeCast<StringOrDouble>()
"""


def log(message: str) -> None:
    print(message, file=sys.stderr)


def pascal(name: str) -> str:
    parts = [part for part in re.split(r"[^0-9A-Za-z]+", name) if part]
    return "".join(part[:1].upper() + part[1:] for part in parts) or "Empty"


def lower_first(name: str) -> str:
    return name[:1].lower() + name[1:] if name else name


def kotlin_identifier(name: str) -> str:
    """A Kotlin-usable name for an upstream member: keywords get a suffix, punctuation `_`."""
    cleaned = re.sub(r"[^0-9A-Za-z_]", "_", name)
    if not cleaned or cleaned[0].isdigit():
        cleaned = "_" + cleaned
    if cleaned in KOTLIN_KEYWORDS:
        cleaned += "_"
    return cleaned


def indent(text: str, prefix: str) -> str:
    return "\n".join(prefix + line if line else prefix.rstrip() for line in text.splitlines())


def strip_comment(block: str) -> str:
    """Turns a `/** ... */` TypeScript block into a KDoc block, indentation normalised."""
    body = block.strip()
    if body.startswith("/**"):
        body = body[3:]
    if body.endswith("*/"):
        body = body[:-2]
    lines = [re.sub(r"^\s*\*+\s?", "", line).rstrip() for line in body.splitlines()]
    while lines and not lines[0]:
        lines.pop(0)
    while lines and not lines[-1]:
        lines.pop()
    if not lines:
        return ""
    lines = [line.replace("*/", "*&#47;") for line in lines]
    return "\n".join(["/**"] + [f" * {line}" if line else " *" for line in lines] + [" */"])


class Union:
    def __init__(self, name: str, literals: list[str], numbers: list[str], doc: str):
        self.name = name
        self.literals = literals
        self.numbers = numbers
        self.doc = doc


class Generator:
    def __init__(self, dts: str, version: str):
        self.dts = dts
        self.version = version
        self.source = open(dts, encoding="utf-8").read()
        self.decls: list[dict] = []
        self.unions: dict[tuple, Union] = {}
        self.union_names: dict[str, tuple] = {}
        self.emitted: list[str] = []
        self.known: set[str] = {"StringOrDouble"}
        self.unresolved: set[str] = set()

    # -- parsing ---------------------------------------------------------------------------

    def parse(self) -> None:
        text = re.sub(r"^import .*?;$", "", self.source, flags=re.M)
        pattern = re.compile(r"export (interface|type) ([A-Za-z0-9_]+)")
        index = 0
        while True:
            match = pattern.search(text, index)
            if not match:
                break
            kind, name = match.group(1), match.group(2)
            self.known.add(name)
            if kind == "interface":
                body_start = text.index("{", match.end())
                extends = self.parse_extends(text[match.end(): body_start])
                body = self.capture_braces(text, body_start)
                decl = {
                    "kind": "interface",
                    "name": name,
                    "extends": extends,
                    "members": self.parse_members(body, name),
                    "doc": self.leading_doc(match.start()),
                }
                index = body_start + len(body)
            else:
                body_start = text.index("=", match.end()) + 1
                body = self.capture_alias(text, body_start)
                decl = {
                    "kind": "type",
                    "name": name,
                    "value": body.strip(),
                    "doc": self.leading_doc(match.start()),
                }
                index = body_start + len(body)
            self.decls.append(decl)

    def leading_doc(self, position: int) -> str:
        head = self.source[:position].rstrip()
        if not head.endswith("*/"):
            return ""
        return strip_comment(head[head.rfind("/**"):])

    @staticmethod
    def parse_extends(head: str) -> list[str]:
        match = re.search(r"extends", head)
        if not match:
            return []
        return re.findall(r"[A-Za-z0-9_]+", head[match.end():])

    @staticmethod
    def capture_braces(text: str, start: int) -> str:
        depth = 0
        for position in range(start, len(text)):
            if text[position] == "{":
                depth += 1
            elif text[position] == "}":
                depth -= 1
                if depth == 0:
                    return text[start: position + 1]
        raise ValueError("unbalanced braces")

    @staticmethod
    def capture_alias(text: str, start: int) -> str:
        depth = 0
        for position in range(start, len(text)):
            char = text[position]
            if char in "{([":
                depth += 1
            elif char in "})]":
                depth -= 1
            elif char == ";" and depth == 0:
                return text[start:position]
        raise ValueError("unterminated type alias")

    def parse_members(self, body: str, owner: str) -> list[dict]:
        inner = body.strip()[1:-1]
        members: list[dict] = []
        index = 0
        pending_doc = ""
        while index < len(inner):
            char = inner[index]
            if char in " \t\r\n":
                index += 1
                continue
            if inner.startswith("/**", index):
                end = index + inner[index:].index("*/") + 2
                pending_doc = strip_comment(inner[index:end])
                index = end
                continue
            member_start = re.compile(r"'[^']*'\??\s*:|[A-Za-z_$][A-Za-z0-9_$]*\??\s*:").match(inner, index)
            if member_start:
                colon = inner.index(":", index)
                end = self.scan_to_semicolon(inner, colon)
                head = inner[index:colon].strip()
                member = {
                    "name": head.rstrip("?").strip().strip("'"),
                    "optional": head.endswith("?"),
                    "type": inner[colon + 1: end],
                    "doc": pending_doc,
                }
                pending_doc = ""
                index = end + 1
                members.append(member)
                continue
            index_signature = re.compile(r"\[[^\]]*\]\s*:\s*").match(inner, index)
            if index_signature:
                end = self.scan_to_semicolon(inner, index_signature.end())
                members.append(
                    {
                        "name": None,
                        "optional": True,
                        "type": inner[index_signature.end(): end],
                        "doc": pending_doc,
                    }
                )
                pending_doc = ""
                index = end + 1
                continue
            if char == ";":
                index += 1
                continue
            raise ValueError(f"unparsed member in {owner}: {inner[index:index + 80]!r}")

        for member in members:
            if member["name"] is None:
                continue
            type_text = member["type"].strip()
            if not (type_text.startswith("{") and type_text.endswith("}")):
                continue
            hoisted = owner + pascal(member["name"])
            self.known.add(hoisted)
            hoisted_members = self.parse_members(type_text, hoisted)
            if any(item["name"] is None for item in hoisted_members):
                # A pure record: `{[key: string]: string}` becomes `Record<String, V>`.
                value_type = hoisted_members[0]["type"].strip()
                self.emitted.append(
                    self.emit_typealias(
                        hoisted, f"Record<String, {self.map_type(value_type, hoisted, hoisted)}>",
                        member["doc"],
                    )
                )
            else:
                self.emitted.append(
                    self.emit_interface(hoisted, [], hoisted_members, member["doc"])
                )
            member["type"] = hoisted
        return members

    @staticmethod
    def scan_to_semicolon(text: str, start: int) -> int:
        depth = 0
        for position in range(start, len(text)):
            char = text[position]
            if char in "{([":
                depth += 1
            elif char in "})]":
                depth -= 1
            elif char == ";" and depth == 0:
                return position
        raise ValueError("unterminated member")

    # -- type mapping ----------------------------------------------------------------------

    def map_type(self, ts_type: str, hint: str, doc: str) -> str:
        text = " ".join(ts_type.split()).rstrip(";").strip()
        while text.startswith("(") and text.endswith(")") and self.balanced(text[1:-1]):
            text = text[1:-1].strip()

        simple = {
            "number": "Double",
            "string": "String",
            "boolean": "Boolean",
            "any": "JsAny",
            "unknown": "JsAny",
            "object": "JsAny",
            "null": "Nothing?",
        }
        if text in simple:
            return simple[text]
        if text == "string[]":
            return "Array<String>"

        parts = self.split_union(text)
        if len(parts) > 1:
            if [part for part in parts if part not in ("string", "number")] == []:
                return "StringOrDouble"
            return self.map_union(parts, hint, doc)
        single = parts[0]

        if "=>" in single:
            return self.map_function(single, hint, doc)
        if re.match(r"^[A-Za-z0-9_$]+$", single):
            if single not in self.known:
                self.unresolved.add(single)
            return single
        if single.endswith("[]"):
            return f"Array<{self.map_type(single[:-2], hint, doc)}>"
        if single.startswith("Partial<") and single.endswith(">"):
            return self.map_type(single[len("Partial<"):-1], hint, doc)
        if single.startswith("Record<") and single.endswith(">"):
            key, value = [part.strip() for part in self.split_top(single[len("Record<"):-1], ",")]
            return f"Record<{self.map_type(key, hint, doc)}, {self.map_type(value, hint, doc)}>"
        if single.startswith("import("):
            return "JsAny"
        raise ValueError(f"unmapped type {ts_type!r} (hint {hint})")

    def map_function(self, text: str, hint: str, doc: str) -> str:
        arrow = text.index("=>")
        head = text[:arrow].strip()
        result = text[arrow + 2:].strip()
        params = head
        if head.startswith("(") and head.endswith(")"):
            params = head[1:-1].strip()
        parameters = []
        if params:
            for part in self.split_top(params, ","):
                part = part.strip()
                if not part:
                    continue
                if part.endswith("?"):
                    self.optional_parameter = True
                    part = part[:-1].strip()
                if ":" in part:
                    part = part.split(":", 1)[1].strip()
                parameters.append(self.map_type(part, hint, doc))
        result_type = self.map_type(result, hint, doc)
        signature = "(" + ", ".join(parameters) + ") -> " + result_type
        if getattr(self, "optional_parameter", False) and len(parameters) == 1:
            signature = f"({parameters[0]}?) -> {result_type}"
        self.optional_parameter = False
        return signature

    @staticmethod
    def balanced(text: str) -> bool:
        depth = 0
        for char in text:
            if char in "{([<":
                depth += 1
            elif char in "})]>":
                depth -= 1
                if depth < 0:
                    return False
        return depth == 0

    @staticmethod
    def split_union(text: str) -> list[str]:
        return [part.strip() for part in Generator.split_top(text, "|")]

    @staticmethod
    def split_top(text: str, separator: str) -> list[str]:
        parts: list[str] = []
        depth = 0
        start = 0
        for position, char in enumerate(text):
            if char in "{([<":
                depth += 1
            elif char in "})]>":
                depth -= 1
            elif char == separator and depth == 0:
                parts.append(text[start:position])
                start = position + 1
        parts.append(text[start:])
        return parts

    def map_union(self, parts: list[str], hint: str, doc: str) -> str:
        parts = self.flatten_unions(parts)
        literals = [part for part in parts if re.match(r"'[^']*'$", part)]
        numbers = [part for part in parts if re.match(r"^[-0-9.]+$", part)]
        nulls = [part for part in parts if part in ("null", "undefined")]
        others = [part for part in parts if part not in literals and part not in numbers and part not in nulls]

        if not others:
            if nulls and not literals and not numbers:
                raise ValueError(f"union of nullables is handled by the caller: {parts!r}")
            key = ("literal", tuple(sorted(literals)), tuple(sorted(numbers)))
            if key not in self.unions:
                union = self.new_union(hint, key, [item[1:-1] for item in literals], numbers, doc)
                self.emitted.append(self.emit_literal_union(union))
            if nulls:
                return self.unions[key].name + "?"
            return self.unions[key].name

        mapped = [self.map_type(part, hint, doc) for part in others]
        if nulls:
            if len(mapped) == 1 and not literals and not numbers:
                return mapped[0] + "?"
            raise ValueError(f"unmapped nullable union {parts!r} (hint {hint})")
        if len(mapped) == 1 and not literals and not numbers:
            return mapped[0]
        members = list(dict.fromkeys(mapped))
        if literals:
            members.append("String")
        if numbers:
            members.append("Double")
        members = [member for member in dict.fromkeys(members) if member != hint]
        key = ("union", tuple(sorted(members)))
        if key not in self.unions:
            union = self.new_union(hint, key, [item[1:-1] for item in literals], numbers, doc)
            self.emitted.append(self.emit_opaque_union(union, members))
        return self.unions[key].name

    @staticmethod
    def flatten_unions(parts: list[str]) -> list[str]:
        """`boolean | ('arc' | 'gap')` is the same union as `boolean | 'arc' | 'gap'`."""
        flat: list[str] = []
        for part in parts:
            inner = part.strip()
            if inner.startswith("(") and inner.endswith(")") and Generator.balanced(inner[1:-1]):
                flat.extend(Generator.flatten_unions(Generator.split_union(inner[1:-1])))
            else:
                flat.append(inner)
        return flat

    def new_union(self, hint: str, key: tuple, literals: list[str], numbers: list[str], doc: str) -> Union:
        name = hint
        if name in self.union_names and self.union_names[name] != key:
            # Two different upstream unions mapped to the same field-derived name: keep both, the
            # second one gets a numeric suffix so the declaration stays unique.
            index = 2
            while f"{hint}{index}" in self.union_names:
                index += 1
            name = f"{hint}{index}"
            log(f"note: union {hint} already taken, renamed to {name}")
        self.union_names[name] = key
        union = Union(name, literals, numbers, doc)
        self.unions[key] = union
        self.known.add(name)
        return union


    # -- emission --------------------------------------------------------------------------

    def emit_interface(
        self, name: str, extends: list[str], members: list[dict], doc: str, inherited: dict | None = None
    ) -> str:
        parents = "".join(f" : {parent}" for parent in extends)
        inherited = inherited or {}
        lines = []
        if doc:
            lines.append(doc)
        lines.append(f"external interface {name}{parents} {{")
        blocks: list[str] = []
        for member in members:
            if member["name"] is None:
                continue
            hint = name + pascal(member["name"])
            type_text = self.map_type(member["type"], hint, "")
            kotlin_name = kotlin_identifier(member["name"])
            annotation = ""
            modifiers = ""
            if member["name"] in inherited:
                # Kotlin requires the member to be marked as an override. When the subtype
                # narrows the inherited type, the member is redeclared under a Kotlin name and
                # mapped back with `@JsName` (`ktjs-type-mapping` §12).
                parent_name, parent_type = inherited[member["name"]]
                parent_mapped = self.map_type(parent_type, parent_name + pascal(member["name"]), "")
                if parent_mapped != type_text:
                    kotlin_name = "typed" + kotlin_name[:1].upper() + kotlin_name[1:]
                    annotation = f'    @JsName("{member["name"]}")\n'
                modifiers = "override "
            elif kotlin_name != member["name"]:
                annotation = f'    @JsName("{member["name"]}")\n'
            optional = "" if type_text.endswith("?") else "?"
            block = []
            if member["doc"]:
                block.append(indent(member["doc"], "    "))
            block.append(f"{annotation}    {modifiers}var {kotlin_name}: {type_text}{optional}")
            blocks.append("\n".join(block))
        lines.append("\n\n".join(blocks))
        lines.append("}")
        return "\n".join(lines)

    @staticmethod
    def emit_typealias(name: str, value: str, doc: str) -> str:
        lines = []
        if doc:
            lines.append(doc)
        lines.append(f"typealias {name} = {value}")
        return "\n".join(lines)

    @staticmethod
    def emit_literal_union(union: Union) -> str:
        lines = []
        if union.doc:
            lines.append(union.doc)
        lines.append(f"sealed external interface {union.name}")
        factories = []
        if union.literals:
            literals = ", ".join(f'`"{literal}"`' for literal in union.literals)
            factories.append(
                f"/** Wraps one of the upstream literals: {literals}. */\n"
                f'@Suppress("NOTHING_TO_INLINE")\n'
                f"inline fun {union.name}(value: String): {union.name} =\n"
                f"    value.unsafeCast<{union.name}>()"
            )
        if union.numbers:
            # One factory for every numeric member: the JS side cannot tell `0` from `1`, and
            # two `(value: Double)` overloads would be a conflicting declaration.
            numbers = ", ".join(f"`{number}`" for number in union.numbers)
            factories.append(
                f"/** Wraps the numeric member of the union: {numbers}. */\n"
                f'@Suppress("NOTHING_TO_INLINE")\n'
                f"inline fun {union.name}(value: Double): {union.name} =\n"
                f"    value.unsafeCast<{union.name}>()"
            )
        lines.append("\n\n".join(factories))
        for part in Generator.emit_constants(union, union.name, "sealed external interface"):
            lines.append(part)
        return "\n".join(lines)

    @staticmethod
    def constants_object(name: str) -> str:
        """`X` → `Xs`, but `…Hops` would become `…Hopss`, so names ending in `s` get `Values`."""
        return f"{name}Values" if name.endswith("s") else f"{name}s"

    @classmethod
    def emit_constants(cls, union: Union, name: str, opening: str) -> list[str]:
        if not union.literals:
            return []
        constants = []
        for literal in union.literals:
            constant = lower_first(pascal(literal))
            if constant in KOTLIN_KEYWORDS:
                constant = f"`{constant}`"
            constants.append(
                f'/** `"{literal}"` */\n'
                f"inline val {constant}: {name}\n"
                f'    get() = "{literal}".unsafeCast<{name}>()'
            )
        return [
            f"/** Wire values of [{name}], as the upstream literals. */",
            f"object {cls.constants_object(name)} {{",
            "\n\n".join(indent(item, "    ") for item in constants),
            "}",
        ]

    @classmethod
    def emit_opaque_union(cls, union: Union, members: list[str]) -> str:
        lines = []
        if union.doc:
            lines.append(union.doc)
        lines.append(f"external interface {union.name}")
        factories = [
            f'/** Wraps the `{member}` member of the union. */\n'
            f'@Suppress("NOTHING_TO_INLINE")\n'
            f"inline fun {union.name}(value: {member}): {union.name} =\n"
            f"    value.unsafeCast<{union.name}>()"
            for member in members
        ]
        lines.append("\n\n".join(factories))
        lines.extend(cls.emit_constants(union, union.name, "external interface"))
        return "\n\n".join(lines)

    def inherited_members(self, decl: dict) -> dict:
        """Member names an interface inherits, with the type the nearest ancestor declares."""
        result: dict = {}
        by_name = {item["name"]: item for item in self.decls if item["kind"] == "interface"}
        pending = list(decl["extends"])
        while pending:
            parent = pending.pop(0)
            parent_decl = by_name.get(parent)
            if parent_decl is None:
                continue
            for member in parent_decl["members"]:
                if member["name"] is None:
                    continue
                result.setdefault(member["name"], (parent, member["type"]))
            pending.extend(parent_decl["extends"])
        return result

    def run(self) -> None:
        self.parse()
        for decl in self.decls:
            if decl["kind"] == "interface":
                self.emitted.append(self.emit_interface(
                    decl["name"], decl["extends"], decl["members"], decl["doc"],
                    self.inherited_members(decl)))
                continue
            value = decl["value"]
            doc = decl["doc"]
            if "import(" in value:
                note = ("外键（`import(...)`）属于其他包的类型，本 wrapper 不引用那个包的声明，"
                        "按上游语义保留为 [JsAny]。")
                if doc:
                    doc = doc[: doc.rfind("*/")].rstrip() + f"\n *\n * {note}\n */"
                else:
                    doc = f"/**\n * {note}\n */"
            mapped = self.map_type(value, decl["name"], doc)
            if mapped == decl["name"]:
                # `type X = 'a' | 'b'`: the union already took the alias's name, and a typealias
                # to itself would be a redeclaration.
                continue
            self.emitted.append(self.emit_typealias(decl["name"], mapped, doc))

        if self.unresolved:
            log(f"unresolved upstream type names: {sorted(self.unresolved)}")
        body = "\n\n".join(part for part in self.emitted if part)
        text = HEADER.format(version=self.version, package=PKG) + "\n" + PRELUDE + "\n" + body + "\n"
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        log(f"wrote {OUT}: {len(text.splitlines())} lines, "
            f"{len(self.decls)} declarations, {len(self.unions)} unions")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dts", default=DEFAULT_DTS)
    parser.add_argument("--version", default="12.3.0")
    args = parser.parse_args()
    if not os.path.exists(args.dts):
        raise SystemExit(f"missing {args.dts}: run ./gradlew kotlinNpmInstall, or pass --dts PATH")
    Generator(args.dts, args.version).run()


if __name__ == "__main__":
    main()
